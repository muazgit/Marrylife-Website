async function seed() {
  console.log("Starting seed process...");

  // Get user_id from seed bot
  const { data: users } = await supabase.auth.admin.listUsers();
  const seedUser = users.users.find((u) => u.email === "seed_bot@marrylife.com");
  if (!seedUser) {
    throw new Error("Seed user not found!");
  }
  const userId = seedUser.id;
  console.log("Using seed userId:", userId);

  let successCount = 0;

  for (const item of SEED_DATA) {
    const { contact, ...biodataData } = item;

    const { data: insertedBiodata, error: bError } = await supabase
      .from("biodatas")
      .insert({
        ...biodataData,
        user_id: userId,
        status: "approved",
        approved_at: new Date().toISOString(),
      })
      .select()
      .single();

    if (bError) {
      console.error("Error inserting biodata:", bError);
      continue;
    }

    // Insert contact details
    const { error: cError } = await supabase.from("biodata_contacts").insert({
      ...contact,
      biodata_id: insertedBiodata.id,
    });

    if (cError) {
      console.error("Error inserting contact for biodata:", insertedBiodata.id, cError);
    } else {
      successCount++;
      console.log(
        `✓ Inserted Biodata ML-${insertedBiodata.biodata_number} (${insertedBiodata.gender}, ${insertedBiodata.permanent_division})`,
      );
    }
  }

  console.log(`\n🎉 Seed completed! Successfully inserted ${successCount} biodatas.`);
}

seed().catch(console.error);
